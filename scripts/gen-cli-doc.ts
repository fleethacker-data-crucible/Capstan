// Keeps the commands table in docs/CLI.md in step with the command registry. The table lives between
// two marker comments and is generated; everything else in the file is written by hand.
//
//   bun scripts/gen-cli-doc.ts          rewrite the table in docs/CLI.md
//   bun scripts/gen-cli-doc.ts --check  exit 1 if docs/CLI.md is out of date (changes nothing)
//
// Exit codes: 0 done or up to date, 1 out of date (--check), 2 usage error or the markers are missing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type CommandDescription, type CommandsDocument, describeCommands } from '../src/engine/commands/registry';

export const START_MARKER = '<!-- commands:start -->';
export const END_MARKER = '<!-- commands:end -->';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CLI_DOC_PATH = join(root, 'docs', 'CLI.md');

const kebab = (name: string): string => name.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const cell = (text: string): string => text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const sentence = (text: string): string => (/[.!?]$/.test(text.trim()) ? text.trim() : `${text.trim()}.`);

type Input = CommandDescription['inputs'][number];

/** One option as it reads in the table: `--flag` and, in brackets, what it needs. */
export function describeOption(i: Input): string {
  const bits: string[] = [];
  if (i.required) bits.push('required');
  if (i.type === 'enum' && i.values) bits.push(i.values.join(', '));
  if (i.type === 'number') {
    const n = (v: number) => String(Number(v.toPrecision(3))); // 1/30 reads as 0.0333, not 0.03333333333333333
    const range =
      i.min !== undefined && i.max !== undefined ? `${n(i.min)} to ${n(i.max)}` : i.min !== undefined ? `${n(i.min)} or more` : i.max !== undefined ? `up to ${n(i.max)}` : '';
    const whole = i.integer ? 'whole number' : '';
    const text = [whole, range].filter(Boolean).join(' ');
    if (text) bits.push(text);
  }
  if (i.type === 'id' && i.many) bits.push('one or more ids');
  if (i.type === 'json') bits.push('JSON');
  return `\`--${kebab(i.name)}\`${bits.length ? ` (${bits.join('; ')})` : ''}`;
}

function row(c: CommandDescription): string {
  const what = [sentence(c.summary)];
  if (c.atLeastOne?.length) what.push(`Give at least one of ${c.atLeastOne.map((n) => `\`--${kebab(n)}\``).join(', ')}.`);
  if (c.destructive) what.push('**Needs `--yes`.**');
  if (c.needs === 'browser') what.push('Browser only.');
  return `| \`${c.name}\` | ${cell(what.join(' '))} | ${cell(c.inputs.map(describeOption).join(', '))} |`;
}

/** The generated text that goes between the markers (no markers, no trailing newline). */
export function renderCommandsBlock(doc: CommandsDocument = describeCommands()): string {
  const all = doc.commands;
  const browser = all.filter((c) => c.needs === 'browser').length;
  const destructive = all.filter((c) => c.destructive).length;
  return [
    '<!-- Generated by scripts/gen-cli-doc.ts from the command registry. Do not edit by hand: change the registry, then run `bun scripts/gen-cli-doc.ts`. -->',
    '',
    `${all.length} commands: ${all.length - browser} run over plain project data and ${browser} are browser only (marked below). ${destructive} need \`--yes\`.`,
    '',
    '| Command | What it does | Options |',
    '|---|---|---|',
    ...all.map(row),
  ].join('\n');
}

/** `current` (the text of CLI.md) with the block between the markers replaced. Throws when a marker is missing. */
export function applyCommandsBlock(current: string, block: string = renderCommandsBlock()): string {
  const text = current.replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const a = text.indexOf(START_MARKER);
  const b = text.indexOf(END_MARKER);
  if (a < 0 || b < 0 || b < a) throw new Error(`docs/CLI.md needs ${START_MARKER} and then ${END_MARKER}`);
  return `${text.slice(0, a)}${START_MARKER}\n${block}\n${text.slice(b)}`;
}

/** What `--check` finds: the file as it is and as it should be. */
export function checkCliDoc(path: string = CLI_DOC_PATH): { upToDate: boolean; current: string; expected: string } {
  const current = readFileSync(path, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const expected = applyCommandsBlock(current);
  return { upToDate: current === expected, current, expected };
}

function main(args: string[]): number {
  const check = args.includes('--check');
  if (args.some((a) => a !== '--check')) {
    console.error('Usage: bun scripts/gen-cli-doc.ts [--check]');
    return 2;
  }
  let result: ReturnType<typeof checkCliDoc>;
  try {
    result = checkCliDoc();
  } catch (e) {
    console.error((e as Error).message);
    return 2;
  }
  if (check) {
    if (result.upToDate) return 0;
    console.error('docs/CLI.md is out of date with the command registry. Run: bun scripts/gen-cli-doc.ts');
    return 1;
  }
  if (result.upToDate) {
    console.error('docs/CLI.md is already up to date');
    return 0;
  }
  // A string is written as UTF-8 with no byte order mark.
  writeFileSync(CLI_DOC_PATH, result.expected, 'utf8');
  console.error(`Wrote ${CLI_DOC_PATH}`);
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
