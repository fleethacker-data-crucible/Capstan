// Icons drawn filled rather than outlined.
const FILLED = new Set(['record', 'play']);

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

// Shared fleet HTML/SVG comment stripper. `<!-->` and `<!--->` are empty comments.
function commentEnd(s, from) {
  for (let j = from; j < s.length - 2; j++) {
    if (s[j] !== '-' || s[j + 1] !== '-') continue;
    if (s[j + 2] === '>') return j + 3;
    if (s[j + 2] === '!' && s[j + 3] === '>') return j + 4;
  }
  return -1;
}
function stripOnce(s) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    const start = s.indexOf('<!--', i);
    if (start < 0) return out + s.slice(i);
    out += s.slice(i, start);
    if (s[start + 4] === '>') { i = start + 5; continue; }
    if (s[start + 4] === '-' && s[start + 5] === '>') { i = start + 6; continue; }
    const end = commentEnd(s, start + 4);
    if (end < 0) return out;
    i = end;
  }
  return out;
}
export function stripHtmlComments(input) {
  let cur = String(input);
  let prev;
  do { prev = cur; cur = stripOnce(cur); } while (cur !== prev);
  return cur;
}

/** The JSX inside one Lucide `<svg>`, comments removed and attributes camel-cased. */
export function iconInner(svg) {
  return stripHtmlComments(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (_, a) => ` ${camel(a)}=`)
    .trim();
}

function main() {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
    process.exit(1);
  }
  const entries = Object.entries(ICONS).map(([name, lucide]) => {
    const svg = readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
    const inner = iconInner(svg);
    const body = inner.includes('><') || (inner.match(/</g) || []).length > 1 ? `<>${inner}</>` : inner;
    return `  ${name}: ${body}, // ${lucide}`;
  });

  const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// Drawn at 16 px in controls and 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
import type { ReactElement } from 'react';

const paths: Record<string, ReactElement> = {
${entries.join('\n')}
};
const filled = new Set<string>(${JSON.stringify([...FILLED])});

export type IconName = keyof typeof paths;

export function Icon({ name, size = 16, label }: { name: IconName; size?: number; label?: string }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled.has(name) ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    >
      {paths[name]}
    </svg>
  );
}
`;
  const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui', 'icons.tsx');
  writeFileSync(target, out);
  console.log(`wrote ${entries.length} icons to ${target}`);
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isDirect) main();
