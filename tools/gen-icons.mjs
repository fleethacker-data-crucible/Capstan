// Generates src/ui/icons.tsx from Lucide's SVG sources, so the app bundles only the icons it uses
// and never loads anything from a CDN (docs/UNIFIED-UI.md section 6).
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// The output is committed; re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// Capstan's icon name -> Lucide icon name.
const ICONS = {
  record: 'circle',
  import: 'download',
  undo: 'undo-2',
  redo: 'redo-2',
  split: 'scissors',
  power: 'power',
  trash: 'trash-2',
  play: 'play',
  pause: 'pause',
  stepBack: 'step-back',
  stepForward: 'step-forward',
  toStart: 'skip-back',
  export: 'upload',
  eye: 'eye',
  eyeOff: 'eye-off',
  speaker: 'volume-2',
  speakerOff: 'volume-x',
  lock: 'lock',
  unlock: 'lock-open',
  plus: 'plus',
  close: 'x',
  zoomIn: 'zoom-in',
  zoomOut: 'zoom-out',
  film: 'film',
  wave: 'audio-waveform',
  image: 'image',
  newDoc: 'file-plus',
  open: 'folder-open',
  save: 'save',
  copy: 'copy',
  magnet: 'magnet',
  editor: 'clapperboard',
  keyboard: 'keyboard',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  collapse: 'panel-left-close',
  expand: 'panel-left-open',
};
// Icons drawn filled rather than outlined.
const FILLED = new Set(['record', 'play']);

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
  process.exit(1);
}
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const entries = Object.entries(ICONS).map(([name, lucide]) => {
  const svg = readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (_, a) => ` ${camel(a)}=`)
    .trim();
  const body = inner.includes('><') || (inner.match(/</g) || []).length > 1 ? `<>${inner}</>` : inner;
  return `  ${name}: ${body}, // ${lucide}`;
});

const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// Drawn at 16 px in controls and 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
import type { ReactElement } from 'react';

const paths: Record<string, ReactElement> = {
${entries.join('\n')}
};
const filled = new Set<string>(${JSON.stringify([...FILLED])});

export type IconName = keyof typeof paths;

export function Icon({ name, size = 16, label }: { name: IconName; size?: number; label?: string }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled.has(name) ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    >
      {paths[name]}
    </svg>
  );
}
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui', 'icons.tsx');
writeFileSync(target, out);
console.log(`wrote ${entries.length} icons to ${target}`);
